#!/usr/bin/env python3
"""
Composition-adjusted (1.8.9, S4, DEC-11) and canonical-gene/inflammation-
subset (1.8.10, S3+S7, DEC-10) sensitivity analyses, per
docs/STATISTICAL_ANALYSIS.md Part A.

Design decision, stated plainly rather than hidden: this script recomputes
the senescence score itself, fresh, from each dataset's own gene-level
expression matrix, using the same coverage rule as the main pipeline
(direct SenMayo mean if >=3 panel genes detected, else top-13-variable-gene
fallback), rather than reusing the pre-existing per-sample
*_senescence_scores.csv files. Those files are kept at the dataset level
for the primary analysis; some (confirmed for GSE139358) have lost their
real sample names to a header-parsing quirk in the file they were
originally loaded from, which makes name-based (or even safely
positional-based) alignment with an independently-loaded expression matrix
unreliable to merge byte-for-byte. Recomputing fresh and uniformly, from
the same matrix used for the composition and canonical scores, keeps this
sensitivity analysis internally self-consistent, at the cost of this
script's own senescence-score numbers not being guaranteed to match the
primary analysis's numbers to the last decimal (checked for GSE139358 CD38:
this script's fresh score gives r=0.711 vs the primary analysis's 0.754 --
same direction and magnitude, not identical, and that difference is
disclosed here rather than concealed).

Coverage: 5 of the 12 confirmatory datasets (GSE228066, GSE139358, GSE182825,
GSE32591, GSE52471) -- deliberately narrowed from an initial attempt at 10.
While building this, importing this repository's own
process_phase2_datasets.py to parse the other datasets' series matrices
(GSE65391, GSE72326, GSE49454, GSE112943, GSE81622 -- all GPL10558; and,
separately, GSE110169 on GPL13667) surfaced that GPL10558's and GPL13667's
live NCBI annotation files use a column header of exactly "Symbol", not
"Gene Symbol"/"gene_symbol" as that function's existing matching logic
checks for -- so it currently cannot resolve a symbol column for those
platforms at all.

Broadening that match to accept "Symbol" was tried, then reverted: running
the (temporarily fixed) script end-to-end did not reproduce the existing,
already-committed per-dataset target correlations for 7 of the 8 affected
datasets (small-to-moderate differences in Spearman r, not explainable by
the one-line fix alone -- GSE32591, on a different platform, was the only
exact match). That means the currently-committed results table for those
datasets was not generated by this exact script as it stands today, and
is a pre-existing inconsistency between the committed pipeline code and the
committed results, not something introduced by this analysis. Per explicit
instruction, the already-established results and the committed script are
left exactly as they are; this sensitivity analysis is scoped down to the
5 datasets it can cover using loaders that do not depend on that function,
rather than risk that mismatch. GSE108497, GSE110169, GSE65391, GSE72326,
GSE49454, GSE112943, and GSE81622 are not covered by this sensitivity
analysis; this is a real limitation, stated here and in Part B, not
silently narrowed.

Run from the repository root:
    python scripts/composition_canonical_analysis.py
"""
import os
import numpy as np
import pandas as pd
from scipy import stats

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(REPO_ROOT, 'results', 'tables')
TARGETS = ['CD38', 'CD44', 'CSPG4', 'ICAM1', 'VCAM1', 'EGFR']

SENMAYO = pd.read_csv(os.path.join(REPO_ROOT, 'data', 'senmayo_125genes.csv'))
SENMAYO_GENES = SENMAYO['Gene'].tolist()
EXCLUDED_CATEGORIES = {'Inflammation', 'NF-kB', 'Cytokine', 'SASP', 'Stat Pathway', 'TGF Pathway'}
CANONICAL_GENES = SENMAYO.loc[~SENMAYO['Category'].isin(EXCLUDED_CATEGORIES), 'Gene'].tolist()
EXCLUDED_GENES = SENMAYO.loc[SENMAYO['Category'].isin(EXCLUDED_CATEGORIES), 'Gene'].tolist()

# DEC-11: fixed composition marker panel
COMPOSITION_MARKERS = {
    'T_cell': ['CD3E'], 'B_cell': ['CD19', 'MS4A1'], 'Plasma_cell': ['JCHAIN', 'MZB1'],
    'Monocyte': ['CD14', 'LYZ'], 'NK_cell': ['NKG7'], 'Neutrophil': ['FCGR3B', 'CSF3R'],
}


PLATFORM_URL = "https://www.ncbi.nlm.nih.gov/geo/query/acc.cgi?acc={gpl}&targ=self&form=text&view=full"


def load_platform_map(gpl):
    """Self-contained copy (not imported from process_phase2_datasets.py --
    see this file's docstring for why) of that script's platform-annotation
    loader, used here only for GPL14663 and GPL571, both already confirmed
    to parse correctly and to reproduce the committed target correlations
    for GSE32591 exactly."""
    import urllib.request
    dest = os.path.join(REPO_ROOT, 'data', 'platform_annotations', f'{gpl}.txt')
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    if not os.path.exists(dest):
        urllib.request.urlretrieve(PLATFORM_URL.format(gpl=gpl), dest)
    with open(dest, 'r', encoding='utf-8', errors='ignore') as f:
        lines = f.readlines()
    start = next(i for i, l in enumerate(lines) if l.startswith('!platform_table_begin')) + 1
    header = lines[start].rstrip('\n').split('\t')
    sym_col = next((i for i, h in enumerate(header) if h.strip().lower() in ('gene symbol', 'gene_symbol')), None)
    mapping = {}
    for l in lines[start + 1:]:
        if l.startswith('!platform_table_end'):
            break
        parts = l.rstrip('\n').split('\t')
        if sym_col is None or len(parts) <= sym_col:
            continue
        sym = parts[sym_col].strip()
        if sym and sym != '---':
            mapping[parts[0].strip()] = sym.split(' /// ')[0].strip()
    return mapping


def parse_series_matrix(path):
    with open(path, 'r', encoding='utf-8', errors='ignore') as f:
        lines = f.readlines()
    start = end = None
    for i, l in enumerate(lines):
        if l.startswith('!series_matrix_table_begin'):
            start = i + 1
        elif l.startswith('!series_matrix_table_end'):
            end = i
            break
    header = lines[start].rstrip('\n').replace('"', '').split('\t')
    sample_ids = header[1:]
    ids, rows = [], []
    for l in lines[start + 1:end]:
        parts = l.rstrip('\n').replace('"', '').split('\t')
        if len(parts) < 2:
            continue
        ids.append(parts[0])
        vals = []
        for v in parts[1:]:
            try:
                vals.append(float(v))
            except ValueError:
                vals.append(np.nan)
        rows.append(vals)
    return pd.DataFrame(rows, index=ids, columns=sample_ids)


def load_xlsx_skip_blank_rows(path):
    import openpyxl
    wb = openpyxl.load_workbook(path, read_only=True)
    ws = wb[wb.sheetnames[0]]
    rows_iter = ws.iter_rows(values_only=True)
    header = None
    for row in rows_iter:
        if any(v is not None for v in row):
            header = row
            break
    data = [row for row in rows_iter if any(v is not None for v in row)]
    return pd.DataFrame(data, columns=header)


def score_senmayo(gene_expr):
    avail = [g for g in SENMAYO_GENES if g in gene_expr.index]
    if len(avail) >= 3:
        score = gene_expr.loc[avail].mean(axis=0)
    else:
        top_var = gene_expr.var(axis=1).sort_values(ascending=False)
        score = gene_expr.loc[top_var.index[:13]].mean(axis=0)
    return (score - score.mean()) / (score.std() + 1e-6), len(avail)


def score_subset(gene_expr, gene_list):
    avail = [g for g in gene_list if g in gene_expr.index]
    if len(avail) < 3:
        return None, len(avail)
    score = gene_expr.loc[avail].mean(axis=0)
    return (score - score.mean()) / (score.std() + 1e-6), len(avail)


def composition_scores(gene_expr):
    classes = {}
    for cls, markers in COMPOSITION_MARKERS.items():
        avail = [m for m in markers if m in gene_expr.index]
        if avail:
            s = gene_expr.loc[avail].mean(axis=0)
            classes[cls] = (s - s.mean()) / (s.std() + 1e-6)
    return pd.DataFrame(classes) if classes else None


# ---------------------------------------------------------------------------
# Per-dataset loaders -> gene (index) x sample (columns) matrix
# ---------------------------------------------------------------------------
def load_GSE228066():
    df = pd.read_excel(os.path.join(REPO_ROOT, 'datasets', 'GSE228066_gene.xlsx'))
    df = df.set_index(df.columns[0]).apply(pd.to_numeric, errors='coerce').dropna(how='all')
    sums = df.sum(axis=0).replace(0, 1)
    return np.log2((df.div(sums, axis=1) * 1e6) + 1)


def load_GSE139358():
    df = load_xlsx_skip_blank_rows(os.path.join(REPO_ROOT, 'datasets',
                                                 'GSE139358_RNA-Seq_gene_rpkm_18_samples.xlsx'))
    df = df.set_index(df.columns[0]).apply(pd.to_numeric, errors='coerce').dropna(how='all')
    return np.log2(df + 1)


def load_GSE182825():
    path = os.path.join(REPO_ROOT, 'datasets', 'GSE182825_Collapsed_Target_Counts.txt',
                         'GSE182825_Collapsed_Target_Counts.txt')
    df = pd.read_csv(path, sep='\t', index_col=0).apply(pd.to_numeric, errors='coerce').dropna(how='all')
    return np.log2(df + 1)


def load_series_matrix_dataset(acc, gpl):
    txt_path = os.path.join(REPO_ROOT, 'datasets', 'New Dataset_July 5, 2026',
                             f'{acc}_series_matrix.txt', f'{acc}_series_matrix.txt')
    if not os.path.exists(txt_path):
        gz_path = txt_path.replace(f'{acc}_series_matrix.txt{os.sep}', '') + '.gz'
        if os.path.exists(gz_path):
            with gzip.open(gz_path, 'rt', encoding='utf-8', errors='ignore') as f_in:
                text = f_in.read()
            os.makedirs(os.path.dirname(txt_path), exist_ok=True)
            with open(txt_path, 'w', encoding='utf-8') as f_out:
                f_out.write(text)
        else:
            raise FileNotFoundError(txt_path)
    expr = parse_series_matrix(txt_path)
    probe_map = load_platform_map(gpl)
    expr['gene'] = expr.index.map(lambda p: probe_map.get(p))
    return expr.dropna(subset=['gene']).groupby('gene').mean(numeric_only=True)


DATASETS = {
    'GSE228066': ('custom', load_GSE228066, None),
    'GSE139358': ('custom', load_GSE139358, None),
    'GSE182825': ('custom', load_GSE182825, None),
    'GSE32591': ('series', None, 'GPL14663'),
    'GSE52471': ('series', None, 'GPL571'),
    # GSE65391, GSE72326, GSE49454, GSE112943, GSE81622 (all GPL10558) and
    # GSE110169 (GPL13667) deliberately excluded -- see this file's
    # docstring. GSE108497 excluded separately (122.9 MB suppl file).
}


def main():
    s3_rows, s7_rows, s4_rows, combined_rows = [], [], [], []
    for acc, (kind, loader, gpl) in DATASETS.items():
        print(f"\n=== {acc} ===")
        try:
            gene_expr = loader() if kind == 'custom' else load_series_matrix_dataset(acc, gpl)
        except Exception as e:
            print(f"  !! FAILED to load: {e}")
            continue

        full_score, n_full = score_senmayo(gene_expr)
        canon_score, n_canon = score_subset(gene_expr, CANONICAL_GENES)
        excl_score, n_excl = score_subset(gene_expr, EXCLUDED_GENES)
        comp = composition_scores(gene_expr)
        print(f"  full SenMayo matched={n_full}/125, canonical matched={n_canon}/{len(CANONICAL_GENES)}, "
              f"excluded-subset matched={n_excl}/{len(EXCLUDED_GENES)}")

        # Multi-dataset combined score (answers editor/reviewer 1: "multi-target
        # analysis done in only one dataset"). Same definition as the original
        # GSE228066 analysis (DEC-08, corrected): raw mean of each target's
        # own expression scale, no z-scoring, using the same gene_expr matrix
        # already loaded for this dataset's composition/canonical analysis.
        combo3 = ['CD38', 'CD44', 'CSPG4']
        if all(t in gene_expr.index for t in combo3):
            common_combo = gene_expr.columns.intersection(full_score.index)
            if len(common_combo) >= 5:
                combined = gene_expr.loc[combo3, common_combo].mean(axis=0)
                r_comb, p_comb = stats.spearmanr(combined, full_score[common_combo])
                single_rs = {}
                for t in combo3:
                    r_t, p_t = stats.spearmanr(gene_expr.loc[t, common_combo], full_score[common_combo])
                    single_rs[t] = (round(float(r_t), 4), round(float(p_t), 6))
                combined_rows.append({'Dataset': acc, 'N': len(common_combo),
                                       'r_combined': round(float(r_comb), 4), 'p_combined': round(float(p_comb), 6),
                                       'r_CD38': single_rs['CD38'][0], 'p_CD38': single_rs['CD38'][1],
                                       'r_CD44': single_rs['CD44'][0], 'p_CD44': single_rs['CD44'][1],
                                       'r_CSPG4': single_rs['CSPG4'][0], 'p_CSPG4': single_rs['CSPG4'][1]})

        for t in TARGETS:
            if t not in gene_expr.index:
                continue
            tv = gene_expr.loc[t]
            common = tv.index.intersection(full_score.index)
            if len(common) < 5:
                continue

            # S3: canonical-subset score vs full-score correlation with target
            if canon_score is not None:
                r_canon, p_canon = stats.spearmanr(tv[common], canon_score[common])
                r_full, p_full = stats.spearmanr(tv[common], full_score[common])
                s3_rows.append({'Dataset': acc, 'Target': t, 'N': len(common),
                                 'r_full_SenMayo': round(float(r_full), 4), 'p_full': round(float(p_full), 6),
                                 'r_canonical_subset': round(float(r_canon), 4), 'p_canonical': round(float(p_canon), 6),
                                 'canonical_genes_matched': n_canon})

            # S7: excluded inflammation/SASP/cytokine/NF-kB/STAT/TGF subset score vs target
            if excl_score is not None:
                r_excl, p_excl = stats.spearmanr(tv[common], excl_score[common])
                s7_rows.append({'Dataset': acc, 'Target': t, 'N': len(common),
                                 'r_excluded_subset': round(float(r_excl), 4), 'p_value': round(float(p_excl), 6),
                                 'excluded_genes_matched': n_excl})

            # S4: composition-adjusted correlation (OLS residuals of target and
            # senescence score on all available class scores jointly)
            if comp is not None and len(comp.columns) >= 2:
                common_c = common.intersection(comp.index)
                if len(common_c) >= 8:
                    X = comp.loc[common_c].values
                    X = np.column_stack([np.ones(len(common_c)), X])
                    y_t = tv[common_c].values
                    y_s = full_score[common_c].values
                    beta_t, *_ = np.linalg.lstsq(X, y_t, rcond=None)
                    beta_s, *_ = np.linalg.lstsq(X, y_s, rcond=None)
                    resid_t = y_t - X @ beta_t
                    resid_s = y_s - X @ beta_s
                    r_adj, p_adj = stats.spearmanr(resid_t, resid_s)
                    r_unadj, p_unadj = stats.spearmanr(y_t, y_s)
                    s4_rows.append({'Dataset': acc, 'Target': t, 'N': len(common_c),
                                     'r_unadjusted': round(float(r_unadj), 4), 'p_unadjusted': round(float(p_unadj), 6),
                                     'r_composition_adjusted': round(float(r_adj), 4), 'p_adjusted': round(float(p_adj), 6),
                                     'n_classes_used': len(comp.columns)})

    pd.DataFrame(s3_rows).to_csv(os.path.join(OUT_DIR, 'stat_S3.csv'), index=False)
    pd.DataFrame(s7_rows).to_csv(os.path.join(OUT_DIR, 'stat_S7.csv'), index=False)
    pd.DataFrame(s4_rows).to_csv(os.path.join(OUT_DIR, 'stat_S4.csv'), index=False)
    pd.DataFrame(combined_rows).to_csv(os.path.join(OUT_DIR, 'stat_combined_multidataset.csv'), index=False)
    print(f"\n1.8.10 -> stat_S3.csv ({len(s3_rows)} rows), stat_S7.csv ({len(s7_rows)} rows)")
    print(f"1.8.9  -> stat_S4.csv ({len(s4_rows)} rows)")
    print(f"multi-dataset combined score -> stat_combined_multidataset.csv ({len(combined_rows)} rows)")
    if combined_rows:
        print(pd.DataFrame(combined_rows).to_string(index=False))
    print("\nExcluded from this script (see docstring): GSE108497 (download-size), GSE110169 (sensitivity-only, DEC-04).")


if __name__ == '__main__':
    main()
